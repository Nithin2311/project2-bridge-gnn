"""Generate macros.tex for the report: every result number the prose quotes, read from the artifact tables.

Lookups: \\res{run}{target}{column} (eval/tables/runs_agg.csv), \\pair{run}{reference}{target}{column}
(eval/tables/paired.csv), \\strat{run}{target}{stratum}{level}{column} (eval/tables/strata.csv, first seed), plus scalar \\newcommand macros for graph sizes, motif statistics, the pre-2020 rebuild,
and cohort counts supplied by the caller. An unknown key is a LaTeX error, never an empty string.
"""
from __future__ import annotations

import argparse
import math
from pathlib import Path

import polars as pl

RES_COLUMNS = ["auroc_mean", "auroc_sd", "auprc_mean", "auprc_sd", "brier_mean", "auroc_seed", "auroc_lo", "auroc_hi",
               "auprc_seed", "auprc_lo", "auprc_hi", "n", "pos"]
INT_COLUMNS = {"n", "pos"}
PAIR_COLUMNS = ["d_auroc", "d_auroc_lo", "d_auroc_hi", "d_auprc", "d_auprc_lo", "d_auprc_hi"]
MAIN_RUNS = ["G-gcn", "G-sage", "G-gat", "B-prevalence", "B-lr", "B-hgb", "B-hgb_all", "B-mlp", "B-mlp_pool", "B-bridge_lr"]
PRIMARY_TARGETS = ["cardiometabolic", "cancer_hematologic", "mental_health"]
# scalar macros: name -> (file, filter column, filter value, value column, format)
LAYER_SCALARS = {
    "nNodesU": ("U", "n_nodes", "{:d}"), "nEdgesU": ("U", "n_edges", "{:d}"), "nIsolatesU": ("U", "n_isolates", "{:d}"),
    "nEdgesD": ("D", "n_edges", "{:d}"), "nIsolatesD": ("D", "n_isolates", "{:d}"),
    "nEdgesBH": ("U-bh", "n_edges", "{:d}"), "nEdgesBB": ("U-bb", "n_edges", "{:d}"),
}
MOTIF_SCALARS = {"motifZ": ("z", "{:.2f}"), "motifZu": ("z_u", "{:.2f}"), "motifPu": ("p_emp_u", "{:.2f}"), "motifP": ("p_emp", "{:.2f}")}
PRE_SCALARS = {"nEdgesPre": ("n_edges_new", "{:d}"), "preJaccard": ("edge_jaccard", "{:.2f}"), "nDevPre": ("n_dev_patients", "{:d}")}
HEADER = r"""% Generated by scripts/report_macros.py from outputs/artifacts; do not edit. Unknown keys are LaTeX errors.
\makeatletter
\newcommand{\res}[3]{\@ifundefined{res:#1:#2:#3}{\PackageError{macros}{unknown key #1/#2/#3}{}}{\csname res:#1:#2:#3\endcsname}}
\newcommand{\pair}[4]{\@ifundefined{pair:#1:#2:#3:#4}{\PackageError{macros}{unknown key #1/#2/#3/#4}{}}{\csname pair:#1:#2:#3:#4\endcsname}}
\newcommand{\strat}[5]{\@ifundefined{strat:#1:#2:#3:#4:#5}{\PackageError{macros}{unknown key #1/#2/#3/#4/#5}{}}{\csname strat:#1:#2:#3:#4:#5\endcsname}}
\makeatother"""


def tex_escape(s: str) -> str:
    for ch in ["&", "%", "#", "_"]:
        s = s.replace(ch, "\\" + ch)
    return s


def _fmt(value, spec: str) -> str:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return "n/a"
    if spec == "{:d}":
        return str(round(float(value)))
    return spec.format(float(value))


def _csname(prefix: str, parts: list[str], value: str) -> str:
    key = ":".join([prefix, *parts])
    return rf"\expandafter\def\csname {key}\endcsname{{{value}}}"


def _check_main_runs(agg: pl.DataFrame) -> None:
    present = {(r, t) for r, t in agg.select("run_id", "target").iter_rows()}
    bad = []
    for run in MAIN_RUNS:
        for t in PRIMARY_TARGETS:
            if (run, t) not in present:
                bad.append(f"{run}/{t}: missing")
                continue
            n = agg.filter((pl.col("run_id") == run) & (pl.col("target") == t))["n_seeds"][0]
            if int(n) != 5:
                bad.append(f"{run}/{t}: n_seeds={n}")
    if bad:
        raise ValueError("main runs must have five-seed aggregates: " + "; ".join(bad))


def build(artifacts: Path, rows_summary: dict | None) -> str:
    artifacts = Path(artifacts)
    lines = [HEADER]
    agg = pl.read_csv(artifacts / "eval/tables/runs_agg.csv", infer_schema_length=None)
    _check_main_runs(agg)
    for r in agg.sort("run_id", "target").iter_rows(named=True):
        for c in RES_COLUMNS:
            if c in r:
                spec = "{:d}" if c in INT_COLUMNS else "{:.3f}"
                lines.append(_csname("res", [r["run_id"], r["target"], c], _fmt(r[c], spec)))
    paired_f = artifacts / "eval/tables/paired.csv"
    if paired_f.exists():
        paired = pl.read_csv(paired_f, infer_schema_length=None)
        first = paired.sort("seed").group_by("run_id", "baseline", "target", maintain_order=True).first()
        for r in first.iter_rows(named=True):
            for c in PAIR_COLUMNS:
                lines.append(_csname("pair", [r["run_id"], r["baseline"], r["target"], c], _fmt(r[c], "{:+.3f}")))
            lines.append(_csname("pair", [r["run_id"], r["baseline"], r["target"], "seed"], str(int(r["seed"]))))
    strata_f = artifacts / "eval/tables/strata.csv"
    if strata_f.exists():
        st = pl.read_csv(strata_f, infer_schema_length=None)
        first = st.sort("seed").group_by("run_id", "target", "stratum", "level", maintain_order=True).first()
        for r in first.iter_rows(named=True):
            key = [r["run_id"], r["target"], r["stratum"], tex_escape(str(r["level"]))]
            for c, spec in (("auroc", "{:.3f}"), ("auprc", "{:.3f}"), ("n", "{:d}"), ("pos", "{:d}")):
                lines.append(_csname("strat", [*key, c], _fmt(r[c], spec)))
    scalars: dict[str, str] = {}
    layers_f = artifacts / "layers/layer_stats.csv"
    if layers_f.exists():
        ls = pl.read_csv(layers_f, infer_schema_length=None)
        for name, (layer, col, spec) in LAYER_SCALARS.items():
            sub = ls.filter(pl.col("layer") == layer)
            if sub.height and col in sub.columns:
                scalars[name] = _fmt(sub[col][0], spec)
    motifs_f = artifacts / "motifs/triad_census.csv"
    if motifs_f.exists():
        tc = pl.read_csv(motifs_f, infer_schema_length=None).filter(pl.col("triad") == "030T")
        if tc.height:
            for name, (col, spec) in MOTIF_SCALARS.items():
                if col in tc.columns:
                    scalars[name] = _fmt(tc[col][0], spec)
    pre_f = artifacts / "pre2020/summary.csv"
    if pre_f.exists():
        pre = pl.read_csv(pre_f, infer_schema_length=None)
        for name, (col, spec) in PRE_SCALARS.items():
            if col in pre.columns:
                scalars[name] = _fmt(pre[col][0], spec)
        if "empty_cores" in pre.columns:
            scalars["preEmptyCores"] = tex_escape(str(pre["empty_cores"][0] or "none"))
    gnn_f = artifacts / "results/gnn.csv"
    if gnn_f.exists():
        g = pl.read_csv(gnn_f, infer_schema_length=None)
        scalars["nGnnRuns"] = str(g["run_id"].n_unique())
        scalars["nSeeds"] = str(g["seed"].n_unique())
    for k, v in (rows_summary or {}).items():
        scalars[k] = _fmt(v, "{:d}") if isinstance(v, (int, float)) else tex_escape(str(v))
    for k in sorted(scalars):
        lines.append(rf"\newcommand{{\{k}}}{{{scalars[k]}}}")
    return "\n".join(lines) + "\n"


def rows_summary_from(rows_path: Path, cfg: dict) -> dict:
    """Cohort counts from the patient-level rows file (counts only; nothing patient-level leaves this function)."""
    rows = pl.read_parquet(rows_path)
    dev = rows.filter(pl.col("split").is_in(cfg["split"]["dev"]))
    test = rows.filter(pl.col("split") == "test")
    out = {"nRows": rows.select("person_id", "index_date").unique().height, "nRowTargets": rows.height,
           "nDevPatients": dev["person_id"].n_unique(), "nTestPatients": test["person_id"].n_unique(),
           "nPatients": rows["person_id"].n_unique()}
    short = {"cardiometabolic": "CM", "cancer_hematologic": "Heme", "mental_health": "MH", "cancer_metastatic": "Meta"}
    for t, s in short.items():
        sub = rows.filter(pl.col("target") == t)
        out[f"nPos{s}"] = int(sub["positive"].sum())
        out[f"nPosTest{s}"] = int(sub.filter(pl.col("split") == "test")["positive"].sum())
        out[f"nRows{s}"] = sub.height
    return out


def main(argv: list[str] | None = None) -> None:
    from . import config

    cfg = config.load()
    out_dir = config.outputs_dir(cfg)
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--artifacts", type=Path, default=out_dir / "artifacts")
    ap.add_argument("--rows", type=Path, default=out_dir / "rows.parquet")
    ap.add_argument("--out", type=Path, default=config.REPO_ROOT / "report" / "macros.tex")
    args = ap.parse_args(argv)
    summary = rows_summary_from(args.rows, cfg) if args.rows.exists() else None
    text = build(args.artifacts, summary)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({text.count(chr(10))} lines{'' if summary else ', no rows summary'})")
